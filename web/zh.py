def _load(path, default):
    try:
        return json.load(open(path, encoding="utf-8"))
    except Exception:
        return default


def _save(path, data):
    try:
        json.dump(data, open(path, "w", encoding="utf-8"), ensure_ascii=False)
    except Exception:
        pass


def cache():
    global _CACHE
    if _CACHE is None:
        _CACHE = _load(CACHE_PATH, {})
    return _CACHE


def budget():
    global _budget
    today = time.strftime("%Y-%m-%d")
    if _budget is None:
        _budget = _load(BUDGET_PATH, {})
    if _budget.get("date") != today:
        _budget = {"date": today, "used": 0}
    return _budget


def budget_left():
    b = budget()
    return max(0, DAILY_BUDGET - int(b.get("used", 0)))


