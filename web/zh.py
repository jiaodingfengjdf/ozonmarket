def _norm(s):
    return re.sub(r"\s+", " ", str(s or "").lower().replace("ё", "е")).strip()


def dict_lookup(text):
    """词典/短语精确命中"""
    t = _norm(text)
    if not t:
        return None
    if t in COUNTRY_ZH:
        return COUNTRY_ZH[t]
    if t in _ALL:
        return _ALL[t]
    return None


def compose(text):
    """逐词拼装：命中率够高才返回，否则 None（宁可不译也不乱译）"""
    raw = str(text or "")
    words = re.findall(r"[А-Яа-яЁёA-Za-z0-9\-]+", raw)
    if not words:
        return None
    out, hit = [], 0
    for w in words:
        key = _norm(w)
        if key in _ALL:
            out.append(_ALL[key])
            hit += 1
        elif re.fullmatch(r"\d+([.,]\d+)?", w):
            out.append(w)
            hit += 0.5
        else:
            out.append(w)
    if hit / max(1, len(words)) < 0.6:
        return None
    joined = "".join(out)
    return joined if re.search(r"[\u4e00-\u9fff]", joined) else None


def online(text):
    """MyMemory 兜底，带预算与缓存"""
    t = str(text or "").strip()
    if not t or len(t) > 400:
        return None
    b = budget()
    if int(b.get("used", 0)) >= DAILY_BUDGET:
        return None
    url = ("https://api.mymemory.translated.net/get?langpair=ru|zh-CN&q="
           + urllib.parse.quote(t[:400]))
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        data = json.loads(urllib.request.urlopen(req, timeout=12).read().decode("utf-8"))
        zh = ((data.get("responseData") or {}).get("translatedText") or "").strip()
        b["used"] = int(b.get("used", 0)) + 1
        _save(BUDGET_PATH, b)
        if not zh or zh == t or "MYMEMORY WARNING" in zh.upper():
            return None
        return zh
    except Exception:
        return None


def translate(texts, allow_online=True):
    """批量翻译，返回 {原文: 中文 或 None}"""
    result = {}
    with _LOCK:
        c = cache()
        todo = []
        for t in texts:
            if not t:
                continue
            if t in result:
                continue
            zh = dict_lookup(t) or compose(t)      # 词典最权威，优先于缓存
            if zh:
                c[t] = zh
                result[t] = zh
                continue
            if t in c:
                result[t] = c[t]
                continue
            todo.append(t)
        if todo and allow_online:
            for t in todo[:DAILY_BUDGET]:
                if budget_left() <= 0:
                    break
                zh = online(t)
                c[t] = zh
                result[t] = zh
        _save(CACHE_PATH, c)
    for t in texts:
        result.setdefault(t, None)
    return result


def one(text, allow_online=True):
    return translate([text], allow_online).get(text)


def stats():
    c = cache()
    known = sum(1 for v in c.values() if v)
    return {"cached": len(c), "translated": known, "budget_left": budget_left()}
